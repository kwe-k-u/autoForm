const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const ENV_PATH = path.join(ROOT, ".env");
// The extension (background.js / account.js) loads this copy — gitignored,
// since it's only ever needed on a developer's machine or in the packed
// extension build, never served over the web.
const OUT_PATH = path.join(ROOT, "firebase-config.js");
// The landing page is deployed as static files (Firebase Hosting only
// serves the landing/ directory — see firebase.json), so its copy has to
// live inside landing/ and be committed. Firebase's web config values
// (apiKey, projectId, etc.) aren't secrets — Firebase's own docs say
// they're safe to check into source control, since access is controlled
// by Security Rules, not by hiding this config.
const LANDING_OUT_PATH = path.join(ROOT, "landing", "firebase-config.js");

const REQUIRED = [
  "FIREBASE_API_KEY",
  "FIREBASE_AUTH_DOMAIN",
  "FIREBASE_PROJECT_ID",
  "FIREBASE_STORAGE_BUCKET",
  "FIREBASE_MESSAGING_SENDER_ID",
  "FIREBASE_APP_ID"
];

const OPTIONAL = ["FIREBASE_MEASUREMENT_ID", "FIREBASE_DATABASE_URL"];

function parseEnv(text) {
  const out = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function toFirebaseConfig(env) {
  return {
    apiKey: env.FIREBASE_API_KEY,
    authDomain: env.FIREBASE_AUTH_DOMAIN,
    projectId: env.FIREBASE_PROJECT_ID,
    storageBucket: env.FIREBASE_STORAGE_BUCKET,
    messagingSenderId: env.FIREBASE_MESSAGING_SENDER_ID,
    appId: env.FIREBASE_APP_ID,
    measurementId: env.FIREBASE_MEASUREMENT_ID,
    databaseURL: env.FIREBASE_DATABASE_URL
  };
}

function main() {
  if (!fs.existsSync(ENV_PATH)) {
    console.error("Missing " + ENV_PATH + ". Copy .env.example to .env and fill it in.");
    process.exit(1);
  }
  const env = parseEnv(fs.readFileSync(ENV_PATH, "utf8"));
  const missing = REQUIRED.filter((k) => !env[k]);
  if (missing.length) {
    console.error("Missing required values in .env: " + missing.join(", "));
    process.exit(1);
  }
  const config = toFirebaseConfig(env);
  const body = [
    "// Generated by scripts/gen-firebase-config.js — do not edit by hand.",
    "globalThis.FIREBASE_CONFIG = " + JSON.stringify(config, null, 2) + ";",
    "globalThis.FIREBASE_CONFIG_AVAILABLE = true;",
    ""
  ].join("\n");

  fs.writeFileSync(OUT_PATH, body);
  console.log("Wrote " + OUT_PATH + " (project: " + config.projectId + ")");

  fs.writeFileSync(LANDING_OUT_PATH, body);
  console.log("Wrote " + LANDING_OUT_PATH + " (project: " + config.projectId + ")");
}

main();
